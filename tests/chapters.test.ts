import { searchChapters, parseQuery, pageChapters, type ChapterItem } from "../shared/chapters";
let fail = 0;
const eq = (name: string, a: any, b: any) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) fail++; console.log(`${ok ? "ok  " : "FAIL"} ${name}${ok ? "" : `\n     got ${JSON.stringify(a)}\n     want ${JSON.stringify(b)}`}`); };
const mk = (n: number | null, title: string | null = null, kind: any = "regular"): ChapterItem => ({ key: `${kind}:${n}`, number: n == null ? null : String(n), num: n, kind, title, language: "en", releaseAt: null, status: "available" });
const list = [mk(null, "The Prologue", "prologue"), ...Array.from({ length: 180 }, (_, i) => mk(i + 1, i === 0 ? "The Beginning" : i === 41 ? "Day 5 of the war" : null)), mk(5.5, "Interlude"), mk(null, "Summer extra", "extra")];
const nums = (q: string, l = list) => searchChapters(l, q).items.map((c) => c.number ?? c.kind);
const groups = (q: string) => searchChapters(list, q).items.map((c) => `${c.number ?? c.kind}:${c.match}`);
eq("5 exact first, no 15/175", nums("5").slice(0, 2), ["5", "5.5"]);
eq("5 never returns 15 or 175", nums("5").some((n) => ["15", "25", "175"].includes(n!)), false);
eq("5 groups", groups("5").slice(0, 4), ["5:exact", "5.5:related", "42:title", "50:prefix"]);
eq("59 exact", nums("59"), ["59"]);
eq("175 exact", nums("175"), ["175"]);
eq("chapter 59 / ch.59 / #59 / '5 9'", ["chapter 59", "ch.59", "#59", "5 9", " 59 "].map((q) => nums(q)[0]), ["59", "59", "59", "59", "59"]);
eq("decimal 5.5", nums("5.5"), ["5.5"]);
eq("title The Beginning", nums("The Beginning"), ["1"]);
eq("title partial 'beginn'", nums("beginn"), ["1"]);
eq("prologue kind", nums("prologue"), ["prologue"]);
eq("extra kind", nums("extra"), ["extra"]);
eq("nonexistent 999", nums("999"), []);
eq("nonexistent text", nums("zzzz"), []);
eq("059 = 59", parseQuery("059").number, "59");
const pg = pageChapters(list, { page: 2, limit: 50 });
eq("pagination", [pg.page, pg.pages, pg.items.length, pg.total], [2, 4, 50, 183]);
eq("prologue sorts first", pageChapters(list, {}).items[0].kind, "prologue");
eq("desc", pageChapters(list, { sort: "desc" }).items[0].number, "180");
process.exit(fail ? 1 : 0);
